    private void btnInputJamActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInputJamActionPerformed
        if (karyawanAktif instanceof Freelance) {
            String strJam = javax.swing.JOptionPane.showInputDialog(this, "Masukkan jam kerja harian:");
            if (strJam != null && !strJam.trim().isEmpty()) {
                try {
                    int jam = Integer.parseInt(strJam);
                    ((Freelance) karyawanAktif).tambahJamKerjaHarian(jam);
                    javax.swing.JOptionPane.showMessageDialog(this, "Jam kerja berhasil ditambahkan!");
                } catch (NumberFormatException ex) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Input harus berupa angka!");
                }
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Fitur ini hanya untuk karyawan Freelance!");
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnInputJamActionPerformed

