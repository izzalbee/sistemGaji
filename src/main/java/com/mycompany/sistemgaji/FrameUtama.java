    private void inisialisasiData() {
        listKaryawan = new java.util.ArrayList<>();
        
        // Data Dummy
        Jabatan jabManagerIT = new Jabatan("Manager IT", 10000000);
        Jabatan jabFreelance = new Jabatan("Freelance Programmer", 0);
        
        KaryawanTetap k1 = new KaryawanTetap("T-01", "Budi", jabManagerIT, new Tunjangan(6));
        Freelance f1 = new Freelance("F-01", "Siti", jabFreelance, 100000);
        
        listKaryawan.add(k1);
        listKaryawan.add(f1);
        
        // Memasukkan data ke tabel
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tabelKaryawan.getModel();
        model.setRowCount(0); // Kosongkan tabel bawaan
        for (Karyawan k : listKaryawan) {
            model.addRow(new Object[]{k.getId(), k.getNama(), k.getJabatan().getNamaJabatan()});
        }
    }

