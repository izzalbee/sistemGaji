    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String cariId = tfCariId.getText();
        Karyawan karyawanDitemukan = null;

        for (Karyawan k : listKaryawan) {
            if (k.getId().equalsIgnoreCase(cariId)) {
                karyawanDitemukan = k;
                break;
            }
        }

        if (karyawanDitemukan != null) {
            FrameKaryawan frame2 = new FrameKaryawan(this, karyawanDitemukan);
            frame2.setVisible(true);
            this.setVisible(false);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Karyawan tidak ditemukan!");
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnSearchActionPerformed

